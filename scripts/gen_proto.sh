# Generates the Python gRPC stubs for contracts/proto into build/gen/python
# with the pinned grpcio-tools (C++ stubs are generated by CMake, see
# engine/cmake/GrpcProtoGen.cmake). Generated code is never committed.

set -euo pipefail

readonly ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly PYTHON="${PYTHON:-${ROOT}/.venv/bin/python}"
readonly OUT="${ROOT}/build/gen/python"

mkdir -p "${OUT}"
"${PYTHON}" -m grpc_tools.protoc \
  -I "${ROOT}/contracts/proto" \
  --python_out="${OUT}" \
  --pyi_out="${OUT}" \
  --grpc_python_out="${OUT}" \
  "${ROOT}"/contracts/proto/vectra/*.proto
echo "Python stubs written to ${OUT}"
